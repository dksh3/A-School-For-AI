"""1A-2Z skill data model: Skill, scope, lifecycle states, provenance.

Phase 1 (automatic skill generation from agent experience). Skills are
reusable, instructional procedures - DATA the agent reads, never executable
code this package runs. Experiences feed the pipeline; confidence and
lifecycle primitives are reused from core.learner (no second engine).
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import Enum
from typing import Any

NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,63}$")
MAX_FIELD = 4000
MAX_PROCEDURE_STEPS = 40


class SkillState(Enum):
    """Lifecycle of a skill (skill-specific states over the same concepts
    the memory lifecycle uses: active / superseded / archived)."""

    CANDIDATE = "candidate"
    VALIDATING = "validating"
    ACTIVE = "active"
    PROVEN = "proven"
    SUPERSEDED = "superseded"
    ARCHIVED = "archived"


RETRIEVABLE_STATES = frozenset({SkillState.ACTIVE, SkillState.PROVEN})


class SkillScope(Enum):
    """How broadly a skill applies. Narrower scopes never leak wider."""

    SESSION = "session"
    PROJECT = "project"
    AGENT = "agent"
    GLOBAL = "global"


def _now() -> float:
    return datetime.now(UTC).timestamp()


@dataclass(frozen=True, slots=True)
class SkillEvent:
    """One provenance entry in a skill's history (why/when it changed)."""

    version: int
    event: str
    reason: str
    timestamp: float
    confidence: float
    experience_id: str = ""
    actor: str = "skillgen"

    def to_dict(self) -> dict[str, Any]:
        return {
            "version": self.version,
            "event": self.event,
            "reason": self.reason,
            "timestamp": self.timestamp,
            "confidence": self.confidence,
            "experience_id": self.experience_id,
            "actor": self.actor,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> SkillEvent:
        return cls(
            version=int(data.get("version", 1)),
            event=str(data.get("event", "")),
            reason=str(data.get("reason", "")),
            timestamp=float(data.get("timestamp", 0.0)),
            confidence=float(data.get("confidence", 0.5)),
            experience_id=str(data.get("experience_id", "")),
            actor=str(data.get("actor", "skillgen")),
        )


@dataclass(slots=True)
class Skill:
    """A reusable capability generated by 1A-Z2."""

    name: str
    description: str
    purpose: str
    triggers: list[str] = field(default_factory=list)
    inputs: list[str] = field(default_factory=list)
    procedure: list[str] = field(default_factory=list)
    expected_output: str = ""
    constraints: list[str] = field(default_factory=list)
    examples: list[str] = field(default_factory=list)
    confidence: float = 0.5
    created_from: list[str] = field(default_factory=list)
    provenance: dict[str, Any] = field(default_factory=dict)
    version: int = 1
    success_count: int = 0
    failure_count: int = 0
    use_count: int = 0
    state: SkillState = SkillState.CANDIDATE
    scope: SkillScope = SkillScope.SESSION
    agent_id: str = ""
    project_id: str = ""
    session_id: str = ""
    tags: list[str] = field(default_factory=list)
    history: list[SkillEvent] = field(default_factory=list)
    created_at: float = field(default_factory=_now)
    updated_at: float = field(default_factory=_now)

    def bump_version(self, event: str, reason: str, **kw: Any) -> None:
        self.version += 1
        self.updated_at = _now()
        self.history.append(
            SkillEvent(
                version=self.version,
                event=event,
                reason=reason,
                timestamp=self.updated_at,
                confidence=self.confidence,
                **kw,
            )
        )

    def record(self, event: str, reason: str, **kw: Any) -> None:
        self.updated_at = _now()
        self.history.append(
            SkillEvent(
                version=self.version,
                event=event,
                reason=reason,
                timestamp=self.updated_at,
                confidence=self.confidence,
                **kw,
            )
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "description": self.description,
            "purpose": self.purpose,
            "triggers": list(self.triggers),
            "inputs": list(self.inputs),
            "procedure": list(self.procedure),
            "expected_output": self.expected_output,
            "constraints": list(self.constraints),
            "examples": list(self.examples),
            "confidence": self.confidence,
            "created_from": list(self.created_from),
            "provenance": dict(self.provenance),
            "version": self.version,
            "success_count": self.success_count,
            "failure_count": self.failure_count,
            "use_count": self.use_count,
            "state": self.state.value,
            "scope": self.scope.value,
            "agent_id": self.agent_id,
            "project_id": self.project_id,
            "session_id": self.session_id,
            "tags": list(self.tags),
            "history": [e.to_dict() for e in self.history],
            "created_at": self.created_at,
            "updated_at": self.updated_at,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Skill:
        def _str_list(key: str) -> list[str]:
            return [str(x) for x in data.get(key, [])]

        try:
            state = SkillState(str(data.get("state", "candidate")))
        except ValueError:
            state = SkillState.CANDIDATE
        try:
            scope = SkillScope(str(data.get("scope", "session")))
        except ValueError:
            scope = SkillScope.SESSION
        return cls(
            name=str(data.get("name", "")),
            description=str(data.get("description", "")),
            purpose=str(data.get("purpose", "")),
            triggers=_str_list("triggers"),
            inputs=_str_list("inputs"),
            procedure=_str_list("procedure"),
            expected_output=str(data.get("expected_output", "")),
            constraints=_str_list("constraints"),
            examples=_str_list("examples"),
            confidence=float(data.get("confidence", 0.5)),
            created_from=_str_list("created_from"),
            provenance=dict(data.get("provenance", {})),
            version=int(data.get("version", 1)),
            success_count=int(data.get("success_count", 0)),
            failure_count=int(data.get("failure_count", 0)),
            use_count=int(data.get("use_count", 0)),
            state=state,
            scope=scope,
            agent_id=str(data.get("agent_id", "")),
            project_id=str(data.get("project_id", "")),
            session_id=str(data.get("session_id", "")),
            tags=_str_list("tags"),
            history=[SkillEvent.from_dict(e) for e in data.get("history", [])],
            created_at=float(data.get("created_at", 0.0)),
            updated_at=float(data.get("updated_at", 0.0)),
        )

    def to_skill_md(self) -> str:
        """Render as SKILL.md (frontmatter + body) for agent consumption."""
        lines = [
            "---",
            f"name: {self.name}",
            f"description: {self.description}",
            f"state: {self.state.value}",
            f"scope: {self.scope.value}",
            f"version: {self.version}",
            f"confidence: {self.confidence:.2f}",
            f"purpose: {self.purpose}",
            f"triggers: [{', '.join(self.triggers)}]",
            f"created_from: [{', '.join(self.created_from)}]",
            "---",
            "",
            f"# {self.name}",
            "",
            self.purpose,
            "",
            "## When to use",
            *[f"- {t}" for t in self.triggers],
            "",
            "## Inputs",
            *([f"- {i}" for i in self.inputs] or ["- none"]),
            "",
            "## Procedure",
            *[f"{i}. {step}" for i, step in enumerate(self.procedure, 1)],
            "",
            f"## Expected output\n{self.expected_output}",
        ]
        if self.constraints:
            lines += ["", "## Constraints", *[f"- {c}" for c in self.constraints]]
        if self.examples:
            lines += ["", "## Examples", *[f"- {e}" for e in self.examples]]
        lines += [
            "",
            "## Provenance",
            f"- confidence: {self.confidence:.2f}",
            f"- created from: {', '.join(self.created_from) or 'manual'}",
            f"- success/failure: {self.success_count}/{self.failure_count}",
            "",
        ]
        return "\n".join(lines)


def scope_visible(skill: Skill, agent_id: str, project_id: str, session_id: str) -> bool:
    """Scope isolation: can a viewer with this context see the skill?"""
    if skill.scope == SkillScope.GLOBAL:
        return True
    if skill.scope == SkillScope.AGENT:
        return bool(skill.agent_id) and skill.agent_id == agent_id
    if skill.scope == SkillScope.PROJECT:
        return bool(skill.project_id) and skill.project_id == project_id
    if skill.scope == SkillScope.SESSION:
        return bool(skill.session_id) and skill.session_id == session_id
    return False
